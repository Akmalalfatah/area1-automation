CREATE TABLE IF NOT EXISTS productivity_swfm_snapshots (
  period CHAR(7) NOT NULL PRIMARY KEY,
  metadata JSON NOT NULL,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS productivity_swfm_rows (
  period CHAR(7) NOT NULL,
  row_no INT UNSIGNED NOT NULL,
  payload JSON NOT NULL,
  PRIMARY KEY (period,row_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS productivity_pic_roster (
  pic_id CHAR(24) NOT NULL PRIMARY KEY,
  profile JSON NOT NULL,
  settings JSON NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
